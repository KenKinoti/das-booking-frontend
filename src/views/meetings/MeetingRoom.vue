            </select>
          </div>
          <div class="ui-card__body side-body">
            <div v-if="!speechSupported" class="ui-alert ui-alert--warning">
              <i class="fa-solid fa-circle-info"></i><span>Live transcription isn't available in this browser. Type or paste the transcript below — it's summarised when you save.</span>
