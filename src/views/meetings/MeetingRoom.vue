<script>
import { markRaw } from 'vue'
import { apiErrorMessage } from '@/services/api'
import { toast } from '@/composables/useToast'
import { confirmDialog } from '@/composables/useConfirm'
import { formatDateTime } from '@/utils/format'
import { meetingsApi, fmtRange, displayStatus, locationLabel, initials } from '@/services/meetings'

const LANGUAGES = [
  { code: 'en-AU', label: 'English (Australia)' },
  { code: 'en-US', label: 'English (US)' },
  { code: 'en-GB', label: 'English (UK)' },
  { code: 'en-IN', label: 'English (India)' },
  { code: 'en-NZ', label: 'English (New Zealand)' },
  { code: 'sw-KE', label: 'Kiswahili' },
  { code: 'fr-FR', label: 'Français' },
  { code: 'de-DE', label: 'Deutsch' },
  { code: 'es-ES', label: 'Español' },
  { code: 'it-IT', label: 'Italiano' },
  { code: 'pt-BR', label: 'Português (Brasil)' },
  { code: 'zh-CN', label: '中文 (普通话)' },
  { code: 'ja-JP', label: '日本語' },
  { code: 'hi-IN', label: 'हिन्दी' },
  { code: 'ar-SA', label: 'العربية' },
  { code: 'vi-VN', label: 'Tiếng Việt' }
]

function pad(n) {
  return String(n).padStart(2, '0')
}

function readStore(key) {
  try {
    return JSON.parse(localStorage.getItem(key) || 'null')
  } catch {
    return null
  }
}
function writeStore(key, value) {
  try {
    if (value === null) localStorage.removeItem(key)
    else localStorage.setItem(key, JSON.stringify(value))
  } catch {
    /* storage unavailable */
  }
}

export default {
  name: 'MeetingRoom',
  data() {
    const SR = typeof window !== 'undefined' ? window.SpeechRecognition || window.webkitSpeechRecognition : null
    let lang = 'en-AU'
    try {
      lang = localStorage.getItem('meetings.lang') || (navigator.language && LANGUAGES.some((l) => l.code === navigator.language) ? navigator.language : 'en-AU')
    } catch {
      /* ignore */
    }
    return {
      meeting: null,
      loading: true,
      error: '',
      phase: 'lobby', // lobby | in | done
      // media
      stream: null,
      mediaState: 'idle', // idle | requesting | ready | error | unsupported
      mediaError: '',
      micOn: true,
      camOn: true,
      // transcription
      SR,
      speechSupported: !!SR,
      recognizer: null,
      recognizing: false,
      wantTranscribe: false,
      recError: '',
      lang,
      languages: LANGUAGES,
      segments: [],
      interim: '',
      editMode: !SR,
      editText: '',
      notes: '',
      hasDraft: false,
      // save
      saving: false,
      saved: null,
      downloading: false,
      // misc
      joinedAt: null,
      tick: Date.now(),
      timer: null,
      me: { name: '' },
      draftTimer: null
    }
  },
  computed: {
    id() {
      return this.$route.params.id
    },
    draftKey() {
      return `meetings.draft.${this.id}`
    },
    status() {
      return displayStatus(this.meeting, this.tick)
    },
    range() {
      return fmtRange(this.meeting)
    },
    where() {
      if (this.meeting.location_type === 'physical') return this.meeting.location
      return locationLabel(this.meeting)
    },
    participantsLabel() {
      const n = (this.meeting.participants || []).length
      return `${n} ${n === 1 ? 'participant' : 'participants'}`
    },
    hasVideo() {
      return !!this.stream && this.stream.getVideoTracks().length > 0
    },
    hasAudio() {
      return !!this.stream && this.stream.getAudioTracks().length > 0
    },
    elapsed() {
      if (!this.joinedAt) return '00:00'
      const s = Math.max(0, Math.floor((this.tick - this.joinedAt) / 1000))
      const h = Math.floor(s / 3600)
      return (h ? `${h}:` : '') + `${pad(Math.floor((s % 3600) / 60))}:${pad(s % 60)}`
    },
    liveText() {
      return this.segments.map((s) => `[${s.ts}] ${s.speaker}: ${s.text}`).join('\n')
    },
    transcriptText() {
      return (this.editMode || !this.speechSupported ? this.editText : this.liveText).trim()
    },
    wordCount() {
      const t = this.transcriptText.replace(/\[\d{2}:\d{2}:\d{2}\]\s*\w+:/g, ' ')
      return (t.match(/\S+/g) || []).length
    }
  },
  watch: {
    segments: {
      deep: true,
      handler() {
        this.saveDraftSoon()
        this.scrollTranscript()
      }
    },
    editText() {
      this.saveDraftSoon()
    },
    notes() {
      this.saveDraftSoon()
    },
    lang(v) {
      try {
        localStorage.setItem('meetings.lang', v)
      } catch {
        /* ignore */
      }
    },
    phase() {
      this.$nextTick(this.attachVideo)
    }
  },
  async mounted() {
    try {
      const u = JSON.parse(localStorage.getItem('current_user') || 'null')
      if (u) this.me.name = `${u.first_name || ''} ${u.last_name || ''}`.trim() || u.email || ''
    } catch {
      /* ignore */
    }
    this.timer = setInterval(() => (this.tick = Date.now()), 1000)
    window.addEventListener('beforeunload', this.onBeforeUnload)
    await this.load()
    if (this.meeting && this.meeting.status !== 'cancelled' && this.phase === 'lobby') this.startMedia()
  },
  beforeUnmount() {
    this.destroyed = true
    clearInterval(this.timer)
    clearTimeout(this.draftTimer)
    window.removeEventListener('beforeunload', this.onBeforeUnload)
    this.stopTranscription()
    this.stopMedia()
  },
  methods: {
    initials,
    fmtDateTime: formatDateTime,
    nowTs() {
      const d = new Date()
      return `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`
    },
    async load() {
      this.loading = true
      try {
        const { meeting } = await meetingsApi.get(this.id)
        this.meeting = meeting
        if (meeting.has_transcript) {
          try {
            this.saved = await meetingsApi.getTranscript(this.id)
          } catch {
            this.saved = null
          }
        }
        const draft = readStore(this.draftKey)
        if (draft && (draft.segments?.length || draft.editText || draft.notes)) {
          this.segments = draft.segments || []
          this.editText = draft.editText || ''
          this.notes = draft.notes || ''
          this.editMode = !this.speechSupported || !!draft.editMode
          this.hasDraft = true
        } else if (this.saved && (meeting.status === 'completed' || meeting.status === 'cancelled')) {
          this.phase = 'done'
        }
      } catch (err) {
        this.error = err?.response?.status === 404 ? 'Meeting not found' : apiErrorMessage(err, 'Could not load the meeting')
      } finally {
        this.loading = false
      }
    },

    // ---------------- media ----------------
    mediaMessage(err) {
      const name = err?.name || ''
      if (name === 'NotAllowedError' || name === 'SecurityError' || name === 'PermissionDeniedError') return 'Camera and microphone access was blocked. Allow access in your browser (address bar → site permissions), then try again. You can still join, transcribe by typing, and take notes.'
      if (name === 'NotFoundError' || name === 'DevicesNotFoundError' || name === 'OverconstrainedError') return 'No camera or microphone was found on this device. You can still join and take notes or paste a transcript.'
      if (name === 'NotReadableError' || name === 'TrackStartError' || name === 'AbortError') return 'Your camera or microphone is being used by another app. Close it and try again.'
      return 'Could not start your camera or microphone. You can still join without them.'
    },
    async startMedia() {
      this.mediaError = ''
      if (!navigator.mediaDevices || typeof navigator.mediaDevices.getUserMedia !== 'function') {
        this.mediaState = 'unsupported'
        this.mediaError = 'Camera and microphone need a secure (HTTPS) connection and a supported browser. You can still join and take notes.'
        return
      }
      this.stopMedia()
      this.mediaState = 'requesting'
      let stream = null
      let firstErr = null
      try {
        stream = await navigator.mediaDevices.getUserMedia({ video: { width: { ideal: 1280 }, height: { ideal: 720 } }, audio: { echoCancellation: true, noiseSuppression: true } })
      } catch (err) {
        firstErr = err
        // Try whichever device exists on its own (e.g. a laptop without a webcam).
        if (err?.name !== 'NotAllowedError' && err?.name !== 'SecurityError') {
          for (const c of [{ audio: true }, { video: true }]) {
            try {
              stream = await navigator.mediaDevices.getUserMedia(c)
              break
            } catch {
              /* try next */
            }
          }
        }
      }
      if (this.destroyed) {
        stream?.getTracks().forEach((t) => t.stop())
        return
      }
      if (!stream) {
        this.mediaState = 'error'
        this.mediaError = this.mediaMessage(firstErr)
        return
      }
      this.stream = markRaw(stream)
      this.mediaState = 'ready'
      if (firstErr) this.mediaError = stream.getVideoTracks().length ? 'No microphone was found — joining with camera only.' : 'No camera was found — joining with audio only.'
      stream.getAudioTracks().forEach((t) => (t.enabled = this.micOn))
      stream.getVideoTracks().forEach((t) => (t.enabled = this.camOn))
      this.$nextTick(this.attachVideo)
    },
    attachVideo() {
      const v = this.$refs.video
      if (!v || !this.stream) return
      if (v.srcObject !== this.stream) v.srcObject = this.stream
      const p = v.play && v.play()
      if (p && typeof p.catch === 'function') p.catch(() => {})
    },
    stopMedia() {
      if (this.stream) this.stream.getTracks().forEach((t) => t.stop())
      this.stream = null
      const v = this.$refs.video
      if (v) v.srcObject = null
    },
    toggleMic() {
      this.micOn = !this.micOn
      this.stream?.getAudioTracks().forEach((t) => (t.enabled = this.micOn))
      if (this.phase === 'in' && this.wantTranscribe) {
        if (!this.micOn) this.pauseRecognizer()
        else this.startRecognizer()
      }
    },
    toggleCam() {
      this.camOn = !this.camOn
      this.stream?.getVideoTracks().forEach((t) => (t.enabled = this.camOn))
      if (this.camOn) this.$nextTick(this.attachVideo)
    },

    // ---------------- call ----------------
    join() {
      this.phase = 'in'
      this.joinedAt = Date.now()
      this.hasDraft = false
      if (this.meeting.status === 'scheduled') {
        meetingsApi
          .start(this.meeting.id)
          .then((r) => {
            if (r?.meeting) this.meeting = { ...this.meeting, status: r.meeting.status }
          })
          .catch(() => {})
      }
      if (this.speechSupported && !this.editMode) this.toggleTranscription()
    },
    resume() {
      if (this.saved && !this.segments.length && !this.editText) {
        this.editText = this.saved.text || ''
        this.notes = this.saved.notes || ''
        this.editMode = true
      }
      this.phase = 'lobby'
      this.startMedia()
    },
    async leave() {
      if (this.transcriptText || this.notes.trim()) {
        const ok = await confirmDialog({ title: 'Leave without saving?', message: 'Your transcript and notes stay as a draft on this device. Use "End & save" to save them and create a summary.', confirmText: 'Leave' })
        if (!ok) return
      }
      this.stopTranscription()
      this.stopMedia()
      this.$router.push('/meetings')
    },
    onBeforeUnload(e) {
      if (this.phase === 'in' && (this.transcriptText || this.notes.trim())) {
        this.flushDraft()
        e.preventDefault()
        e.returnValue = ''
      }
    },

    // ---------------- transcription ----------------
    toggleTranscription() {
      if (this.wantTranscribe) {
        this.stopTranscription()
        return
      }
      this.recError = ''
      this.wantTranscribe = true
      if (this.micOn) this.startRecognizer()
    },
    startRecognizer() {
      if (!this.SR || this.recognizing) return
      let rec = this.recognizer
      if (!rec) {
        try {
          rec = new this.SR()
        } catch {
          this.speechSupported = false
          this.editMode = true
          this.wantTranscribe = false
          return
        }
        rec.continuous = true
        rec.interimResults = true
        rec.maxAlternatives = 1
        rec.onstart = () => (this.recognizing = true)
        rec.onresult = (e) => {
          let interim = ''
          for (let i = e.resultIndex; i < e.results.length; i++) {
            const r = e.results[i]
            const text = (r[0]?.transcript || '').trim()
            if (!text) continue
            if (r.isFinal) this.pushSegment(text)
            else interim += (interim ? ' ' : '') + text
          }
          this.interim = interim
        }
        rec.onerror = (e) => {
          const err = e?.error
          if (err === 'no-speech' || err === 'aborted') return
          if (err === 'not-allowed' || err === 'service-not-allowed') this.recError = 'Microphone access for transcription was blocked. Allow the microphone for this site, or type the transcript using Edit.'
          else if (err === 'audio-capture') this.recError = 'No microphone is available for transcription. Type or paste the transcript using Edit.'
          else if (err === 'network') this.recError = 'The speech service could not be reached (it needs an internet connection). You can type the transcript using Edit.'
          else if (err === 'language-not-supported') this.recError = 'That language isn’t supported for live transcription. Pick another language.'
          else this.recError = `Transcription stopped (${err || 'unknown error'}).`
          this.wantTranscribe = false
        }
        rec.onend = () => {
          this.recognizing = false
          if (this.interim) {
            this.pushSegment(this.interim)
            this.interim = ''
          }
          // Chrome ends recognition after silence — restart while it's wanted.
          if (this.wantTranscribe && this.micOn && this.phase === 'in') setTimeout(() => this.startRecognizer(), 300)
        }
        this.recognizer = markRaw(rec)
      }
      rec.lang = this.lang
      try {
        rec.start()
      } catch {
        /* already started */
      }
    },
    pauseRecognizer() {
      try {
        this.recognizer?.stop()
      } catch {
        /* ignore */
      }
    },
    stopTranscription() {
      this.wantTranscribe = false
      if (this.recognizer) {
        try {
          this.recognizer.abort()
        } catch {
          /* ignore */
        }
      }
      if (this.interim) {
        this.pushSegment(this.interim)
        this.interim = ''
      }
      this.recognizing = false
    },
    onLangChange() {
      if (this.recognizing) this.pauseRecognizer() // onend restarts with the new language
    },
    pushSegment(text) {
      const ts = this.nowTs()
      const seg = { ts, speaker: 'You', text: text.charAt(0).toUpperCase() + text.slice(1) }
      this.segments.push(seg)
      if (this.editMode) {
        const line = `[${ts}] You: ${seg.text}`
        this.editText = this.editText && !this.editText.endsWith('\n') ? `${this.editText}\n${line}` : this.editText + line
      }
    },
    enterEdit() {
      if (!this.editText.trim()) this.editText = this.liveText
      this.editMode = true
    },
    scrollTranscript() {
      this.$nextTick(() => {
        const el = this.$refs.tbox
        if (el && el.scrollHeight - el.scrollTop - el.clientHeight < 120) el.scrollTop = el.scrollHeight
      })
    },

    // ---------------- drafts & save ----------------
    saveDraftSoon() {
      clearTimeout(this.draftTimer)
      this.draftTimer = setTimeout(this.flushDraft, 800)
    },
    flushDraft() {
      if (this.phase === 'done') return
      const empty = !this.segments.length && !this.editText.trim() && !this.notes.trim()
      writeStore(this.draftKey, empty ? null : { segments: this.segments, editText: this.editText, notes: this.notes, editMode: this.editMode, savedAt: Date.now() })
    },
    async endAndSave() {
      if (this.interim) {
        this.pushSegment(this.interim)
        this.interim = ''
      }
      const text = this.transcriptText
      const notes = this.notes.trim()
      if (!text && !notes) {
        toast.warning('Nothing to save yet — transcribe, type the transcript or add notes first.')
        return
      }
      const ok = await confirmDialog({ title: 'End the meeting and save?', message: 'The transcript and notes are saved, a summary with decisions and action items is generated, and the meeting is marked completed.', confirmText: 'End & save' })
      if (!ok) return
      this.saving = true
      this.stopTranscription()
      try {
        const res = await meetingsApi.saveTranscript(this.meeting.id, { text, notes, language: this.lang, complete: true })
        this.saved = res.transcript
        if (res.meeting) this.meeting = { ...this.meeting, status: res.meeting.status, has_transcript: true }
        clearTimeout(this.draftTimer)
        writeStore(this.draftKey, null)
        this.segments = []
        this.editText = ''
        this.notes = ''
        this.stopMedia()
        this.phase = 'done'
        toast.success('Transcript saved and summarised')
      } catch (err) {
        toast.error(apiErrorMessage(err, 'Could not save the transcript'))
        this.flushDraft()
      } finally {
        this.saving = false
      }
    },
    async downloadTxt() {
      this.downloading = true
      try {
        await meetingsApi.downloadTranscript(this.meeting)
      } catch (err) {
        toast.error(apiErrorMessage(err, 'Could not download the transcript'))
      } finally {
        this.downloading = false
      }
    },
    async copyLink() {
      try {
        await navigator.clipboard.writeText(this.meeting.join_url)
        toast.success('Invite link copied')
      } catch {
        toast.error('Copy failed — select the link and copy it manually')
      }
    }
  }
}
</script>

