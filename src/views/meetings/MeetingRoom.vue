          </details>
          <div class="done-foot">
            <router-link :to="`/meetings?open=${meeting.id}`" class="ui-btn"><i class="fa-regular fa-calendar"></i> View meeting</router-link>
            <router-link to="/meetings" class="ui-btn ui-btn--ghost">Back to meetings</router-link>
          </div>
